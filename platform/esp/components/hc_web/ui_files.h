#ifndef HC_ESP_UI_FILES_H
#define HC_ESP_UI_FILES_H

#include <cstddef>
#include <cstdint>

namespace hc {
namespace esp {
namespace ui {

/// A file of the web UI, compiled into the firmware (doc/web.md): its path below the root ("/index.html"),
/// and its gzip-compressed content, a constant array in the application image's flash.
struct UiFile {
	const char* path;
	const uint8_t* data;
	size_t size;
};

/// The UI's content hash (16 hex digits), the ETag of every file and the UI version of the status.
extern const char kVersion[];

/// The files, sorted by path (strcmp order); generated by tools/gen_ui_files.py at build time.
extern const UiFile kFiles[];
extern const size_t kFileCount;

} // namespace ui
} // namespace esp
} // namespace hc

#endif // HC_ESP_UI_FILES_H
