#!/usr/bin/env python3
# Copyright (c) 2026 Bernhard Haumacher
#
# Compiles the web UI into the firmware (doc/web.md):
#
#   gen_ui_files.py <web/ui/dist> <ui_files.cpp> [<language packs dir>]
#
# Every file of the UI is gzip-compressed (level 9, no name or time stamp, so the output depends on
# the content only) into a constant array of <ui_files.cpp>, which the firmware links into its
# application image; the web server sends it from flash with Content-Encoding: gzip (ui_files.h).
# The table hc::esp::ui::kFiles is sorted by path. hc::esp::ui::kVersion is the UI's content hash
# (the first 16 hex digits of a SHA-256 over all paths and contents), which the device sends as the
# ETag of every file and reports as the UI version.
#
# The language packs (doc/i18n.md) come from <language packs dir> (default: web/ui/lang next to
# dist) as /lang/<code>.json, beside the base language dist/lang/en.json; other files in dist/lang
# (the POSIX build's copies of the packs) are not taken from there.

import gzip
import hashlib
import os
import sys


def main():
    if len(sys.argv) not in (3, 4):
        sys.exit("usage: gen_ui_files.py <web/ui/dist> <ui_files.cpp> [<language packs dir>]")
    source, output = sys.argv[1], sys.argv[2]
    packs = sys.argv[3] if len(sys.argv) == 4 else os.path.join(os.path.dirname(os.path.abspath(source)), "lang")
    if not os.path.isfile(os.path.join(source, "index.html")):
        sys.exit("gen_ui_files.py: %s has no index.html" % source)

    files = []  # (path in the UI, source file)
    for root, dirs, names in os.walk(source):
        dirs.sort()
        for name in sorted(names):
            if name.startswith("."):
                continue
            path = os.path.join(root, name)
            rel = os.path.relpath(path, source).replace(os.sep, "/")
            if rel.startswith("lang/") and rel != "lang/en.json":
                continue
            files.append((rel, path))
    pack_count = 0
    if os.path.isdir(packs):
        for name in sorted(os.listdir(packs)):
            if name.endswith(".json") and not name.startswith(".") and name != "en.json":
                files.append(("lang/" + name, os.path.join(packs, name)))
                pack_count += 1
    files.sort()

    digest = hashlib.sha256()
    raw_total = 0
    packed_total = 0
    arrays = []
    entries = []
    for index, (rel, path) in enumerate(files):
        if '"' in rel or "\\" in rel:
            sys.exit("gen_ui_files.py: unsupported file name %s" % rel)
        with open(path, "rb") as f:
            content = f.read()
        digest.update(rel.encode("utf-8") + b"\0" + len(content).to_bytes(8, "big") + content)
        packed = gzip.compress(content, compresslevel=9, mtime=0)
        lines = []
        for start in range(0, len(packed), 24):
            lines.append("\t" + ",".join("0x%02x" % b for b in packed[start:start + 24]) + ",")
        arrays.append("const uint8_t f%d[] = {\n%s\n};" % (index, "\n".join(lines)))
        entries.append('\t{"/%s", f%d, sizeof(f%d)},' % (rel, index, index))
        raw_total += len(content)
        packed_total += len(packed)
    version = digest.hexdigest()[:16]

    text = """// Generated by platform/esp/tools/gen_ui_files.py from web/ui/dist: do not edit.
// web UI %s: %d files (%d language packs), %d B, gzip %d B

#include "ui_files.h"

namespace hc {
namespace esp {
namespace ui {

namespace {

%s

} // namespace

const char kVersion[] = "%s";

const UiFile kFiles[] = {
%s
};

const size_t kFileCount = sizeof(kFiles) / sizeof(kFiles[0]);

} // namespace ui
} // namespace esp
} // namespace hc
""" % (version, len(files), pack_count, raw_total, packed_total, "\n\n".join(arrays), version, "\n".join(entries))
    # Rewritten only when the content changed, so an unchanged UI does not recompile.
    old = None
    if os.path.isfile(output):
        with open(output, "r", encoding="utf-8") as f:
            old = f.read()
    if old != text:
        os.makedirs(os.path.dirname(os.path.abspath(output)), exist_ok=True)
        with open(output, "w", encoding="utf-8") as f:
            f.write(text)
    print("web UI %s: %d files (%d language packs), %d B, gzip %d B" % (version, len(files), pack_count, raw_total,
                                                                      packed_total))


if __name__ == "__main__":
    main()
